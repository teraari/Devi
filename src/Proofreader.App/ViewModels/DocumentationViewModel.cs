    private void UpdateFilter()
    {
        FilteredSections.Clear();

        var result = _sections.Where(x =>
            string.IsNullOrWhiteSpace(SearchText) ||
            x.Title.Contains(SearchText, System.StringComparison.OrdinalIgnoreCase) ||
            x.Category.Contains(SearchText, System.StringComparison.OrdinalIgnoreCase) ||
            x.Content.Contains(SearchText, System.StringComparison.OrdinalIgnoreCase));

        foreach (var section in result)
            FilteredSections.Add(section);

        OnPropertyChanged(nameof(ResultText));
        OnPropertyChanged(nameof(IsEmpty));

        // Логика выбора: если текущая статья исчезла из фильтра, выбираем первую доступную
        if (SelectedSection != null && !FilteredSections.Contains(SelectedSection))
        {
            SelectedSection = FilteredSections.FirstOrDefault();
        }
        else if (SelectedSection == null && FilteredSections.Count > 0)
        {
            SelectedSection = FilteredSections.FirstOrDefault();
        }
    }

