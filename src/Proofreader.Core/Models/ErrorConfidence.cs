namespace Proofreader.Core.Models;

public enum ErrorConfidence
{
    Low,    // Низкая (нельзя исправлять автоматически, например, "Казнить нельзя помиловать")
    Medium, // Средняя (грамматика, пунктуация - лучше спросить пользователя)
    High    // Высокая (опечатки, раскладка, очевидные паронимы - можно исправлять сразу)
}